void draw_debug_overlay(std::vector<u32>& pixels, int width, int height, const std::string& status,
                        const std::deque<std::string>& lines) {
  if (width <= 0 || height <= 0 || pixels.size() < static_cast<size_t>(width) * height) return;
  const int scale = std::max(1, width / 400 + (width >= 400 ? 1 : 0));
  const int line_h = 9 * scale;
  const int rows = 1 + static_cast<int>(lines.size());
  const int band = std::min(height, rows * line_h + 2 * scale);
  for (int y = 0; y < band; ++y) {
    for (int x = 0; x < width; ++x) {
      u32& p = pixels[static_cast<size_t>(y) * width + x];
      p = (p & 0xFF000000u) | ((p >> 2) & 0x003F3F3Fu);  // a quarter of the brightness
    }
  }
  int y = scale;
  draw_text(pixels, width, height, 2 * scale, y, scale, status, kYellow);
  for (const std::string& line : lines) {
    y += line_h;
    draw_text(pixels, width, height, 2 * scale, y, scale, line, kWhite);
  }
}

