constexpr u32 kWhite = 0xFFFFFFFFu;
constexpr u32 kYellow = 0xFF40FFFFu;  // RGBA bytes: R, G, B, A

void draw_text(std::vector<u32>& px, int w, int h, int x, int y, int scale, const std::string& text, u32 colour) {
  for (unsigned char ch : text) {
    if (x + 5 * scale > w) break;
    const int index = (ch >= 0x20 && ch <= 0x7E) ? ch - 0x20 : '?' - 0x20;
    for (int col = 0; col < 5; ++col) {
      const u8 bits = kFont[index][col];
      for (int row = 0; row < 7; ++row) {
        if (((bits >> row) & 1) == 0) continue;
        for (int sy = 0; sy < scale; ++sy) {
          const int py = y + row * scale + sy;
          if (py < 0 || py >= h) continue;
          for (int sx = 0; sx < scale; ++sx) px[static_cast<size_t>(py) * w + x + col * scale + sx] = colour;
        }
      }
    }
    x += 6 * scale;
  }
}

