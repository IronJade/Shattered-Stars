#pragma once

// The programs' identity on the desktop (port feature): their names, the app ids that group
// their windows in a taskbar, and the icon (res/icon, drawn by tools/make_icon.py; an
// original design, nothing from the discs).
//
// - The app id is the Wayland app_id and the X11 WM_CLASS class, which a Linux desktop
//   matches to an installed <app id>.desktop file (res/linux/) for the taskbar's name and
//   icon; SDL reads it from the app metadata (set_app_metadata, before SDL_Init). The game
//   and setup have their own, so each gets its own taskbar entry, as on Windows.
// - The name also names the program's sound stream in the desktop's volume mixer.
// - The icon: on Windows, the .exe's icon resource (res/windows/app.rc.in), which SDL gives
//   every window it opens; elsewhere set_window_icon, from images compiled into the program.

#include <cstddef>
#include <span>
#include <string>

struct SDL_Surface;
struct SDL_Window;

namespace ss::platform {

inline constexpr const char* kGameName = "Shattered Stars";
inline constexpr const char* kGameAppId = "io.github.IronJade.ShatteredStars";
inline constexpr const char* kSetupName = "Shattered Stars Setup";
inline constexpr const char* kSetupAppId = "io.github.IronJade.ShatteredStars.Setup";

// One embedded icon size: a PNG file's bytes (res/icon/shattered-stars-<size>.png).
struct IconImage {
  int size = 0;
  const unsigned char* png = nullptr;
  std::size_t bytes = 0;
};

// The embedded sizes, smallest first: 64, 128, 256 (generated by engine/CMakeLists.txt).
std::span<const IconImage> icon_images();

// SDL's app metadata: name, version and app id (also the type: "game" or "application").
// Before SDL_Init.
void set_app_metadata(const char* name, const char* version, const char* app_id, bool game);

// The icon as one surface: the smallest embedded size as the image for 100% display scale,
// the larger ones as its alternate (high-DPI) images. nullptr and *error on failure. The
// caller destroys it (SDL_DestroySurface).
SDL_Surface* create_icon_surface(std::string* error = nullptr);

// Gives a window the icon (before it is shown). On Windows it does nothing: the window
// already has the .exe's icon, all its sizes (one SDL_SetWindowIcon image would replace
// them). False with *error when the display can't take one (offscreen; GNOME's Wayland,
// which shows the .desktop file's icon instead); nothing else depends on it.
bool set_window_icon(SDL_Window* window, std::string* error = nullptr);

}  // namespace ss::platform
