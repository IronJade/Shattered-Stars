#!/usr/bin/env python3
"""Write docs/port/catalog/COVERAGE.md: how complete the function catalog is.

catalog_coverage.py [--check]

Per module of docs/port/catalog/functions.csv: the rows by confidence (confirmed / likely /
guess) and by port status:
  ported       the port column names a file (port/..., tools/...) that exists;
  not needed   "(not needed: reason)";
  PsyQ         "(PsyQ: ...)" (a library routine the port replaces with its runtime);
  empty        no port column yet;
  bad path     a port column whose first path does not exist.
The rows with an empty port column or a bad path are listed per module at the end, as
are the "unported" rows (port column "(unported: ...)"): functions a real game reaches
that are not ported yet. Rows whose summary carries "[port partial: ...]" (ported, with a
part still missing) are listed in a section of their own.

--check exits 1 when a port path is missing (for the checkpoint script).
"""
import argparse
import collections
import csv
import os
import re

CATALOG = "docs/port/catalog/functions.csv"
OUT = "docs/port/catalog/COVERAGE.md"
CONF = ("confirmed", "likely", "guess")


def port_status(port):
    p = port.strip()
    if not p:
        return "empty"
    low = p.lower()
    if low.startswith("(not needed"):
        return "not needed"
    if low.startswith("(psyq"):
        return "PsyQ"
    if low.startswith("(unported"):
        return "unported"
    if p.startswith("("):
        return "other"
    path = re.split(r"[\s;,(]", p, maxsplit=1)[0]
    return "ported" if os.path.exists(path) else "bad path"


def partial_note(summary):
    """The text of a "[port partial: ...]" note (brackets inside it balanced), or None."""
    start = summary.find("[port partial:")
    if start < 0:
        return None
    depth = 0
    for i in range(start, len(summary)):
        if summary[i] == "[":
            depth += 1
        elif summary[i] == "]":
            depth -= 1
            if depth == 0:
                return summary[start + len("[port partial:"):i].strip()
    return summary[start + len("[port partial:"):].strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rows = list(csv.reader(open(CATALOG, newline="")))
    head, body = rows[0], rows[1:]
    col = {k: i for i, k in enumerate(head)}
    per = collections.OrderedDict()
    todo = collections.defaultdict(list)
    partial = []
    for r in body:
        r = r + [""] * (len(head) - len(r))
        mod = r[col["module"]]
        m = per.setdefault(mod, collections.Counter())
        m["rows"] += 1
        m[r[col["confidence"]] or "guess"] += 1
        st = port_status(r[col["port"]])
        m[st] += 1
        note = partial_note(r[col["summary"]])
        if note is not None:
            partial.append((mod, r[col["address"]], r[col["name"]], note))
        if st in ("empty", "bad path", "unported", "other"):
            todo[mod].append((st, r[col["address"]], r[col["name"]], r[col["confidence"]], r[col["port"]]))

    total = collections.Counter()
    for m in per.values():
        total.update(m)

    statuses = ("ported", "not needed", "PsyQ", "unported", "empty", "bad path", "other")
    lines = [
        "# Catalog coverage",
        "",
        "Generated by `tools/catalog_coverage.py` from `functions.csv`; do not edit by hand.",
        "",
        "The goal is every function of every program catalogued, confirmed and either ported",
        "or marked not needed. Port status: *ported* (a file), *not needed* (`(not needed:",
        "reason)`), *PsyQ* (a library routine the port's runtime replaces), *unported*",
        "(`(unported: ...)`: a real game reaches it, it is not ported yet), *empty* (not yet",
        "looked at), *bad path* (the named file does not exist).",
        "",
        f"Total: {total['rows']} rows; confirmed {total['confirmed']}, likely {total['likely']}, "
        f"guess {total['guess']}; " + ", ".join(f"{s} {total[s]}" for s in statuses if total[s]) + ".",
        "",
        "| Module | Rows | Confirmed | Likely | Guess | Ported | Not needed | PsyQ | Unported | Empty | Bad path | Other |",
        "|---|" + "---:|" * (4 + len(statuses)),
    ]
    for mod, m in sorted(per.items()):
        cells = [str(m["rows"])] + [str(m[c]) for c in CONF] + [str(m[s]) if m[s] else "" for s in statuses]
        lines.append(f"| {mod} | " + " | ".join(cells) + " |")
    lines.append("")
    if todo:
        lines += ["## Rows to resolve", ""]
        for mod in sorted(todo):
            lines.append(f"### {mod} ({len(todo[mod])})")
            lines.append("")
            for st, addr, name, conf, port in todo[mod]:
                extra = f": {port}" if st in ("unported", "bad path", "other") else ""
                lines.append(f"- {addr} `{name}` ({conf}, {st}{extra})")
            lines.append("")
    if partial:
        lines += ["## Partial ports", "",
                  "Ported functions with a part still missing (`[port partial: ...]` in the summary).", ""]
        for mod, addr, name, note in partial:
            lines.append(f"- {mod} {addr} `{name}`: {note}")
        lines.append("")

    # Read existing file and replace only between markers
    block = "\n".join(lines)
    text = open(OUT).read() if os.path.exists(OUT) else ""
    marker_begin = "<!-- coverage:begin -->"
    marker_end = "<!-- coverage:end -->"
    start = text.find(marker_begin)

    if start == -1:
        # No markers found; insert generated block at the top
        text = marker_begin + "\n" + block + "\n" + marker_end + "\n\n" + text
    else:
        # Replace between markers
        end = text.find(marker_end, start + len(marker_begin))
        if end == -1:
            # Missing end marker; append end marker
            text = text[:start] + marker_begin + "\n" + block + "\n" + marker_end + "\n"
        else:
            # Replace between markers
            tail = text[end + len(marker_end):]
            text = text[:start] + marker_begin + "\n" + block + "\n" + marker_end + tail

    open(OUT, "w").write(text)
    print(f"{OUT}: {total['rows']} rows, empty {total['empty']}, unported {total['unported']}, "
          f"partial {len(partial)}, bad path {total['bad path']}, likely {total['likely']}, guess {total['guess']}")
    if args.check and total["bad path"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
